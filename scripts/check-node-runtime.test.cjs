'use strict';
const assert = require('node:assert/strict');
const { test } = require('node:test');
const { assertPatchedNodeVersion } = require('./check-node-runtime.cjs');
for (const version of ['22.23.4', '22.23.5', '22.24.0', '24.22.1', '24.23.0', '26.12.1', '26.13.0']) {
  test(`accepts patched stable Node ${version}`, () => assert.doesNotThrow(() => assertPatchedNodeVersion(version)));
}
for (const version of ['22.23.1', '22.23.3', '22.22.99', '24.22.0', '24.21.99', '26.12.0', '26.11.99', '20.99.99', '23.99.99', '25.99.99', '28.0.0', '22.23.4-rc.1', 'v22.23.4', '', 'not-a-version']) {
  test(`rejects unpatched or unverified Node ${JSON.stringify(version)}`, () => assert.throws(() => assertPatchedNodeVersion(version), /requires patched Node/));
}

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const shellQuote = (value) => "'" + value.replaceAll("'", "'\\''") + "'";
function launcherFixture(t, version) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'shift-node-gate-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(path.join(root, 'bin'), { recursive: true });
  fs.mkdirSync(path.join(root, 'node-runtime/bin'), { recursive: true });
  fs.mkdirSync(path.join(root, 'node/node_modules/defuddle/dist'), { recursive: true });
  const source = fs.readFileSync(path.join(__dirname, 'package-macos.sh'), 'utf8');
  const launcher = source.match(/cat > "\$runtime\/bin\/defuddle" <<'EOF'\n([\s\S]*?)\nEOF/);
  assert.ok(launcher, 'test the launcher generated by packaging');
  fs.writeFileSync(path.join(root, 'bin/defuddle'), launcher[1], { mode: 0o755 });
  fs.copyFileSync(path.join(__dirname, 'check-node-runtime.cjs'), path.join(root, 'bin/check-node-runtime.cjs'));
  const marker = path.join(root, 'converted');
  fs.writeFileSync(path.join(root, 'node/node_modules/defuddle/dist/cli.js'), `require('node:fs').writeFileSync(${JSON.stringify(marker)}, 'ok');`);
  function interpreter(name, reportedVersion) {
    const shim = path.join(root, `${name}.cjs`);
    fs.writeFileSync(shim, `Object.defineProperty(process.versions, 'node', { value: ${JSON.stringify(reportedVersion)} });`);
    const executable = path.join(root, name);
    fs.writeFileSync(executable, `#!/bin/sh\nexec ${shellQuote(process.execPath)} --require ${shellQuote(shim)} "$@"\n`, { mode: 0o755 });
    return executable;
  }
  const selected = interpreter('selected-node', version);
  fs.symlinkSync(selected, path.join(root, 'node-runtime/bin/node'));
  const override = interpreter('override-node', '22.23.4');
  return {
    run: () => spawnSync(path.join(root, 'bin/defuddle'), ['--help'], { encoding: 'utf8', env: { ...process.env, SHIFT_NODE_BIN: override } }),
    marker,
    root,
    selected,
  };
}
test('managed launcher rejects the old bundled runtime even with a patched system override', (t) => {
  const f = launcherFixture(t, '22.23.1');
  const result = f.run();
  assert.equal(result.status, 1, result.stderr);
  assert.match(result.stderr, /found 22\.23\.1/);
  assert.equal(fs.existsSync(f.marker), false, 'Defuddle must not execute');
});
test('managed launcher permits conversion with its patched bundled runtime', (t) => {
  const f = launcherFixture(t, '22.23.4');
  const result = f.run();
  assert.equal(result.status, 0, result.stderr);
  assert.equal(fs.readFileSync(f.marker, 'utf8'), 'ok');
});
test('managed launcher checks the selected system fallback when no bundled runtime exists', (t) => {
  const f = launcherFixture(t, '24.22.0');
  fs.unlinkSync(path.join(f.root, 'node-runtime/bin/node'));
  const result = spawnSync(path.join(f.root, 'bin/defuddle'), ['--help'], { encoding: 'utf8', env: { ...process.env, SHIFT_NODE_BIN: f.selected } });
  assert.equal(result.status, 1, result.stderr);
  assert.match(result.stderr, /found 24\.22\.0/);
  assert.equal(fs.existsSync(f.marker), false);
});
